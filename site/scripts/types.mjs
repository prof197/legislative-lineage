// The site's TypeScript types, generated from the export's JSON Schema, which the pipeline's
// Pydantic models emit (DESIGN.md#dr-1). `--check` fails when the committed types are stale.
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const SCHEMA = new URL("../../schema/export.schema.json", import.meta.url);
const OUT = new URL("../src/types/export.ts", import.meta.url);

// Pydantic titles every property, which the generator would turn into one alias per field, and
// writes tuples in draft 2020-12's `prefixItems`, which it reads as unknown[]. Drop the former
// and rewrite the latter as draft-07 tuples; the schema's meaning is unchanged.
function normalize(node, isProperty = false) {
  if (Array.isArray(node)) return node.map((n) => normalize(n));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && isProperty) continue;
    if (key === "properties") {
      out.properties = Object.fromEntries(
        Object.entries(value).map(([name, prop]) => [name, normalize(prop, true)]),
      );
    } else if (key === "prefixItems") {
      out.items = normalize(value);
      out.minItems = value.length;
      out.maxItems = value.length;
    } else {
      out[key] = normalize(value);
    }
  }
  return out;
}

const schema = normalize(JSON.parse(await readFile(SCHEMA, "utf8")));
const types = await compile(schema, "Export", {
  bannerComment:
    "// Generated by `npm run types` from schema/export.schema.json. Do not edit by hand.",
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  format: false,
});

if (process.argv.includes("--check")) {
  const committed = await readFile(OUT, "utf8").catch(() => "");
  if (committed !== types) {
    console.error("src/types/export.ts is stale; run `npm run types`");
    process.exit(1);
  }
} else {
  await writeFile(OUT, types);
  console.log("-> src/types/export.ts");
}
